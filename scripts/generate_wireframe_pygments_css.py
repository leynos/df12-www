"""Generate wireframe syntax CSS from its beam palette.

Run ``uv run python scripts/generate_wireframe_pygments_css.py`` after
changing ``YardStyle``. The entire syntax partial is generated; semantic
panel layout remains in ``src/styles/wireframe/content.css``.
"""

from pathlib import Path

from pygments.formatters.html import HtmlFormatter

from df12_pages.wireframe_highlighting import YardStyle
from scripts.pygments_css import token_rules

STYLESHEET = Path(__file__).resolve().parents[1] / "src/styles/wireframe/syntax.css"


def build_css() -> str:
    """Return the syntax partial: scoped token variables and rules from YardStyle."""
    variables, rules = token_rules(
        HtmlFormatter(style=YardStyle, cssclass="wf-syntax"),
        YardStyle,
        "wf-syntax",
        "--wf-syntax-",
        "600",
    )
    lines = [
        "/* Generated by scripts/generate_wireframe_pygments_css.py. */",
        "/* stylelint-disable -- Generated token rules; edit YardStyle. */",
        ":root {",
        *variables,
        "}",
        ".wf-syntax { background: var(--color-panel); }",
        *rules,
        "/* stylelint-enable */",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    STYLESHEET.write_text(build_css(), encoding="utf-8")
