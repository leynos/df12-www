"""Vendor the wireframe plate runtime and posters from a pinned source.

The plates are Three.js scenes from ``leynos/wireframe-3js``. This script
exports the pinned commit from a local checkout into a scratch directory,
applies the site's local patches from ``scripts/wireframe-plates/``, builds
the self-contained ES module with the source's own ``make build`` (``npm ci``
against its committed lockfile, then esbuild), and copies the module, the
posters the site uses, and the Three.js licence into
``src/static/wireframe/assets/vendor/plates/``.

It also writes ``PROVENANCE.txt`` beside them: the pin, each patch's SHA-256,
and each vendored file's SHA-256. A build test reads that record, so a file
changed by hand, or a poster the catalogue names but nobody imported, fails
the suite.

Run it from the repository root::

    make wireframe-plates WIREFRAME_3JS_SOURCE=../wireframe-3js

``--check`` rebuilds into the scratch directory and compares the result with
the vendored files instead of writing them.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PIN = "57be19c6183be36f5d4b811d31ea29bae3fdf251"
REPOSITORY = "https://github.com/leynos/wireframe-3js"
# The plates the sub-site shows. Their captions and roles live in
# templates/wireframe/data/plates.jinja; a test holds the two together.
POSTERS = (
    "03", "04", "06", "07", "08", "11", "12", "15", "17",
    "18", "21", "25", "26", "27", "28", "29", "30",
)  # fmt: skip
PATCHES = Path("scripts/wireframe-plates")
DESTINATION = Path("src/static/wireframe/assets/vendor/plates")


def _sha256(path: Path) -> str:
    """Return the hex SHA-256 of a file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _run(argv: list[str], cwd: Path, stdin: bytes | None = None) -> bytes:
    """Run a fixed command, failing loudly with its output if it fails."""
    completed = subprocess.run(  # noqa: S603 - fixed argv built in this module
        argv, cwd=cwd, input=stdin, capture_output=True, check=False
    )
    if completed.returncode != 0:
        sys.stderr.write(completed.stdout.decode(errors="replace"))
        sys.stderr.write(completed.stderr.decode(errors="replace"))
        message = f"{' '.join(argv)} exited {completed.returncode}"
        raise SystemExit(message)
    return completed.stdout


def _tool(name: str) -> str:
    """Return the absolute path of a required executable."""
    found = shutil.which(name)
    if found is None:
        message = f"{name} is not on PATH"
        raise SystemExit(message)
    return found


def _build(source: Path, scratch: Path) -> dict[str, Path]:
    """Export, patch, and build the pin; map each vendored name to its file."""
    git, tar, make = _tool("git"), _tool("tar"), _tool("make")
    archive = _run([git, "-C", str(source.resolve()), "archive", PIN], cwd=scratch)
    _run([tar, "-x"], cwd=scratch, stdin=archive)
    for patch in sorted(PATCHES.resolve().glob("*.patch")):
        _run([git, "apply", "--verbose", str(patch)], cwd=scratch)
    _run([make, "build"], cwd=scratch)
    files = {"wireframe-plate.js": scratch / "dist" / "wireframe-plate.js"}
    files["three-LICENSE.txt"] = scratch / "node_modules" / "three" / "LICENSE"
    for plate in POSTERS:
        files[f"posters/{plate}.webp"] = scratch / "dist" / "posters" / f"{plate}.webp"
    return files


def _provenance(files: dict[str, Path]) -> str:
    """Render the provenance record for the built files."""
    lines = [
        "# Generated by scripts/import_wireframe_plates.py. Do not edit.",
        f"source {REPOSITORY}",
        f"commit {PIN}",
    ]
    lines += [
        f"patch {_sha256(patch)} {patch.as_posix()}"
        for patch in sorted(PATCHES.glob("*.patch"))
    ]
    lines += [f"file {_sha256(path)} {name}" for name, path in sorted(files.items())]
    return "\n".join(lines) + "\n"


def _differences(files: dict[str, Path], record: str) -> list[str]:
    """List vendored files that do not match a fresh build."""
    drift = [
        name
        for name, built in sorted(files.items())
        if not (DESTINATION / name).is_file()
        or _sha256(DESTINATION / name) != _sha256(built)
    ]
    recorded = DESTINATION / "PROVENANCE.txt"
    if not recorded.is_file() or recorded.read_text(encoding="utf-8") != record:
        drift.append("PROVENANCE.txt")
    return drift


def _write(files: dict[str, Path], record: str) -> None:
    """Replace the vendored directory with the freshly built files."""
    if DESTINATION.exists():
        shutil.rmtree(DESTINATION)
    for name, built in files.items():
        target = DESTINATION / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(built, target)
    (DESTINATION / "PROVENANCE.txt").write_text(record, encoding="utf-8")


def main() -> None:
    """Build the pinned plates and vendor them, or check the vendored copy."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path, help="a wireframe-3js checkout")
    parser.add_argument("--check", action="store_true", help="compare only")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="wireframe-plates-") as name:
        scratch = Path(name)
        files = _build(args.source, scratch)
        record = _provenance(files)
        if args.check:
            drift = _differences(files, record)
            if drift:
                message = f"vendored plates differ from {PIN[:7]}: {drift}"
                raise SystemExit(message)
            print(f"vendored plates match {PIN[:7]}")
            return
        _write(files, record)
    print(f"vendored {len(files)} files from {PIN[:7]} into {DESTINATION}")


if __name__ == "__main__":
    main()
